"""Enumerations for system roles, statuses, and audit events."""

from enum import Enum

class UserRole(str, Enum):
    STUDENT = "STUDENT"
    ADMIN = "ADMIN"
    SERVICEMAN = "SERVICEMAN"

class TicketStatus(str, Enum):
    OPEN = "OPEN"
    IN_PROGRESS = "IN PROGRESS"
    PENDING_CONFIRMATION = "PENDING CONFIRMATION" # Serviceman fixed it, waiting on student
    RESOLVED = "RESOLVED" # Student confirmed it
    CLOSED = "CLOSED"
    DUPLICATE = "DUPLICATE"

class AuditAction(str, Enum):
    USER_LOGIN = "USER_LOGIN"
    LOGIN_FAILED = "LOGIN_FAILED"
    ACCOUNT_LOCKED = "ACCOUNT_LOCKED"
    PASSWORD_CHANGED = "PASSWORD_CHANGED"
    PASSWORD_RESET_OTP = "PASSWORD_RESET_OTP"
    TICKET_CREATED = "TICKET_CREATED"
    TICKET_UPDATED = "TICKET_UPDATED"
    DUPLICATE_LINKED = "DUPLICATE_LINKED"
    STAFF_ASSIGNED = "STAFF_ASSIGNED"
    STATUS_CHANGED = "STATUS_CHANGED"
    TICKET_REOPENED = "TICKET_REOPENED"
    FEEDBACK_SUBMITTED = "FEEDBACK_SUBMITTED"
    CATEGORY_CREATED = "CATEGORY_CREATED"
    CATEGORY_UPDATED = "CATEGORY_UPDATED"
    CATEGORY_DELETED = "CATEGORY_DELETED"
    STUDENT_IMPORTED = "STUDENT_IMPORTED"
    STAFF_CREATED = "STAFF_CREATED"
